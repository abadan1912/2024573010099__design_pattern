package modul_3.bagian_2.latihan;

class Motor {
    // Atribut private (Enkapsulasi)
    private String merk;
    private int tahun;

    // Getter untuk Merk
    public String getMerk() {
        return merk;
    }

    // Setter untuk Merk
    public void setMerk(String merk) {
        this.merk = merk;
    }

    // Getter untuk Tahun
    public int getTahun() {
        return tahun;
    }

    // Setter untuk Tahun
    public void setTahun(int tahun) {
        this.tahun = tahun;
    }
}
